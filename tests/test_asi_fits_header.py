def cards_of(path, **kwargs):
    """Write one frame and return its header as ``[(keyword, value, comment)]``."""
    # The long legacy names become HIERARCH cards on purpose; the writer already
    # silences that warning, and nothing here should turn it back into noise.
    with warnings.catch_warnings():
        warnings.simplefilter("ignore")
        write_fits(path, np.zeros((4, 4), dtype="<u2"), **kwargs)
    header = fits.getheader(path)
    return [(card.keyword, card.value, card.comment) for card in header.cards]


def assert_cards_match(actual, expected):
    """Compare card by card, so a failure names the card that moved."""
    assert [name for name, _, _ in actual] == [name for name, _, _ in expected]
    for (name, value, comment), (_, want_value, want_comment) in zip(actual,
                                                                    expected):
        if isinstance(want_value, float):
            assert value == pytest.approx(want_value), name
        else:
            assert value == want_value, name
        assert comment == want_comment, name


def test_a_full_frames_header_is_card_for_card_what_it_has_always_been(tmp_path):
    assert_cards_match(cards_of(tmp_path / "full.fits", **FULL_KWARGS),
                       FULL_CARDS)


def test_a_frame_with_no_optional_values_omits_exactly_those_cards(tmp_path):
    assert_cards_match(cards_of(tmp_path / "minimal.fits", **MINIMAL_KWARGS),
                       MINIMAL_CARDS)


def test_the_optional_cards_are_the_only_difference_between_the_two(tmp_path):
    """Spelled out, so a card moving *between* the blocks cannot pass unnoticed."""
    full = [name for name, _, _ in cards_of(tmp_path / "a.fits", **FULL_KWARGS)]
    minimal = [name for name, _, _ in cards_of(tmp_path / "b.fits",
                                               **MINIMAL_KWARGS)]
    assert [name for name in full if name not in minimal] == [
        "GAIN", "SETTEMP", "SKYMEAN", "SPLITNUM", "SPLITIDX",
        "BITDEPTH", "CCDGAIN", "SEQNO",
    ]
    assert [name for name in minimal if name not in full] == []


def test_a_split_of_one_writes_no_split_cards(tmp_path):
    """The pair appears only when a slot was actually divided."""
    names = [name for name, _, _ in cards_of(
        tmp_path / "one.fits", **dict(FULL_KWARGS, split_count=1, split_index=1))]
    assert "SPLITNUM" not in names and "SPLITIDX" not in names


def test_writing_refuses_to_overwrite_an_existing_frame(tmp_path):
    path = tmp_path / "frame.fits"
    cards_of(path, **FULL_KWARGS)
    with pytest.raises(OSError):
        cards_of(path, **FULL_KWARGS)


def test_a_failed_capture_is_refused_rather_than_filed_as_an_empty_frame(tmp_path):
    with pytest.raises(ValueError, match="image data is None"):
        write_fits(tmp_path / "none.fits", None, **FULL_KWARGS)


