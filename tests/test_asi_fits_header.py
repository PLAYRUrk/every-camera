"""The exact ASI FITS header, card for card, in order.

``tests/test_asi_archive.py`` already checks that each individual name survives a
round trip. This file checks something the per-name assertions cannot: that the
*whole* header is what it is today — every card, its value, its comment, and the
order they appear in. astropy serialises a header in card order, so pinning the
order pins the bytes.

That matters because the station's processing program was written against
imagerd_rt's output and reads these names positionally in places. It matters more
because the writer is about to be rebuilt on top of a shared core
(``cameras/common/fits.py``) so the Hamamatsu camera can use the same eighteen
core cards: a refactor whose whole promise is "the output does not change" needs
one test that would notice if it did.

The two cases are the two shapes the writer actually produces: a cycle-mode frame
that supplies every optional argument, and a sun-mode frame that supplies none of
them. Between them every conditional branch in ``write_fits`` is covered.

The expected lists were generated by running the writer, not written by hand. To
regenerate them after a *deliberate* header change, run this module as a script:

    python tests/test_asi_fits_header.py
"""
