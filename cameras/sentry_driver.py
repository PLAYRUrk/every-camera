class SentryWorkerConsole(threading.Thread):
    MAX_CONSECUTIVE_ERRORS = 5

    def __init__(self, cam: SentryCamera, output_dir: str, instance_name: str,
                 status_dir: str, capture_seconds: list,
                 service=None, node_name: str = "", setup_mode: bool = False):
        super().__init__(daemon=True)
        self.cam = cam
        self.output_dir = output_dir
        self.instance_name = instance_name
        self.status_dir = status_dir
        self.capture_seconds = sorted(capture_seconds)
        self.setup_mode = bool(setup_mode)
        self._service = service
        self._bus = WorkerBus("sentry", instance_name, status_dir,
                              service=service, node_name=node_name)
        self._stop_event = threading.Event()
        self._shots = 0          # frames published (not necessarily captured)
        self._errors = 0
        self._last_shot = None
        self._last_frame = None
        self._last_seqno = -1
        self._focus_seqno = 0

    def request_stop(self):
        self._stop_event.set()

    def run(self):
        self._bus.prepare_status_dir()

        if not self.cam.is_running():
            console_ui.log("imagerd_rt not running — starting daemon...")
            try:
                self.cam.start()
                time.sleep(2)
            except Exception as exc:
                console_ui.error(f"Could not start imagerd_rt: {exc}")

        if self.setup_mode:
            console_ui.log("Sentry ready for focusing (setup mode) — imagerd_rt "
                           "has no schedule to follow")
            self._save_status(SETUP_STATUS, force=True)
        else:
            console_ui.log("Sentry measurement worker started")
            self._save_status("running", force=True)

        last_fired = (-1, -1)

        while not self._stop_event.is_set():
            now = dt.now()

            fire_key = (now.minute, now.second)
            if now.second in self.capture_seconds and fire_key != last_fired:
                last_fired = fire_key
                seqno = self.cam.get_seqno()
                if seqno != self._last_seqno and seqno > 0:
                    self._last_seqno = seqno
                    self._archive_latest(now)
                    self._send_latest_frame()
                    self._shots += 1
                    self._last_shot = now
                self._save_status(
                    SETUP_STATUS if self.setup_mode else
                    ("running" if self.cam.is_running() else "waiting"),
                    force=True)
            elif now.second not in self.capture_seconds:
                last_fired = (-1, -1)
                self._handle_focus(now)

            self._stop_event.wait(0.1)

        if self.cam.is_running():
            console_ui.log("Stopping imagerd_rt daemon...")
            self.cam.stop()

        self._save_status("stopped", force=True)
        self._bus.shutdown()
        console_ui.log("Sentry measurement worker stopped")

    def _archive_latest(self, now):
        if not self.output_dir:
            return
        path = self.cam.archive_latest_image(self.output_dir, now)
        if path:
            console_ui.log(f"SENTRY archived: {os.path.basename(path)}")

    def _handle_focus(self, now):
        """imagerd_rt owns schedule and exposure: focus just sees each new daemon frame."""
        if self._service is None or not self._service.focus_active():
            return
        # Its own counter: the archive's must still see this frame as new.
        seqno = self.cam.get_seqno()
        if seqno <= 0 or seqno == self._focus_seqno:
            return
        self._focus_seqno = seqno
        frame = self.cam.get_latest_image()
        if frame is not None:
            self._service.publish_frame(frame, now, self.cam.get_metadata())

    def _send_latest_frame(self):
        frame = self.cam.get_latest_image()
        if frame is None:
            self._bus.publish_error(
                "no_frame", "No image available yet (aux/image.fits missing)",
                ts_iso=dt.now().isoformat())
            console_ui.warn("SENTRY: no image.fits available yet")
            return
        try:
            meta = self.cam.get_metadata()
            self._last_frame = frame
            if self._service is not None:
                self._service.publish_frame(frame, dt.now(), meta)
            console_ui.log(f"SENTRY frame published (seqno={self._last_seqno})")
        except Exception as exc:
            self._errors += 1
            self._bus.publish_error("error", str(exc),
                                    ts_iso=dt.now().isoformat())
            console_ui.error(f"SENTRY frame publish: {exc}")

    def _save_status(self, status: str, force: bool = False):
        meta = self.cam.get_metadata()
        seqno = self.cam.get_seqno()
        # The daemon does the measuring, so the schedule runs exactly while it is alive.
        # Focus cannot pause it, and reporting that keeps focus_app from promising to.
        publish_schedule_state(self._service,
                               not self.setup_mode and self.cam.is_running())
        payload = {
            "instance_name": self.instance_name,
            "camera_type": "sentry",
            "pid": os.getpid(),
            "status": status,
            "output_dir": self.output_dir,
            "shots_taken": self._shots,
            "last_shot": self._last_shot.isoformat() if self._last_shot else None,
            "errors": self._errors,
            "seqno": seqno,
            "capture_seconds": self.capture_seconds,
            "daemon_running": self.cam.is_running(),
            "setup_mode": self.setup_mode,
            "last_update": dt.now().isoformat(),
        }
        for key in ("CCDTemp", "Exposure", "Binning", "CCDGain", "FilterPo",
                    "SiteID", "DeviceID"):
            if key in meta:
                payload[key.lower()] = meta[key]
        try:
            system = get_system_info(self.output_dir or None)
            payload["system"] = system
            console_ui.update(disk_free_mb=system.get("disk_free_mb"))
        except Exception:
            pass
        console_ui.update(status=status, frames=self._shots, errors=self._errors,
                          output_dir=self.output_dir,
                          detail=f"seqno {seqno}" if seqno and seqno > 0 else None)
        console_ui.set_section("camera", [
            ("Daemon:", "running" if payload["daemon_running"] else "not running"),
            ("Sequence number:", str(seqno)),
            ("Sensor temperature:", str(meta.get("CCDTemp", "n/a"))),
            ("Exposure / binning:", f"{meta.get('Exposure', '?')} · "
                                    f"{meta.get('Binning', '?')}"),
            ("Filter:", str(meta.get("FilterPo", "?"))),
        ])
        self._bus.publish_status(payload, force=force)


def run_preview_sentry(cam: SentryCamera, instance_name: str):
    preview_path = os.path.join(APP_DIR, f"preview_{instance_name}.fits")
    console_ui.log(f"SENTRY preview: reading {cam._image_file} → {preview_path}")
    console_ui.log("Press Ctrl+C to stop.")

    stop = threading.Event()

    def _stop(sig, frame):
        console_ui.log(f"{stop_signal_name(sig)} — stopping preview…")
        stop.set()
    install_stop_handler(_stop)

    import shutil
    frames = 0
    last_seqno = -1
    t0 = dt.now()

    while not stop.is_set():
        seqno = cam.get_seqno()
        if seqno != last_seqno and cam._image_file.exists():
            last_seqno = seqno
            try:
                shutil.copy2(str(cam._image_file), preview_path)
                frames += 1
                if frames % 5 == 0:
                    elapsed = (dt.now() - t0).total_seconds()
                    fps = frames / elapsed if elapsed > 0 else 0
                    meta = cam.get_metadata()
                    console_ui.log(f"Preview: frame {frames}, {fps:.2f} fps, "
                                   f"seqno={seqno}, "
                                   f"temp={meta.get('CCDTemp', '?')}")
            except Exception as exc:
                console_ui.error(f"Preview copy: {exc}")
        time.sleep(0.5)


def run_console_sentry(config_path=None, preview=False, verbose=False,
                       setup_mode=False):
    from utils import load_config, get_node_name

    cfg = load_config(config_path)
    sentry_cfg = cfg.get("sentry", {})

    node_name = get_node_name(cfg)
    claim = claim_instance_name(sentry_cfg.get("instance_name")
                                or get_instance_name("Sentry", cfg))
    instance_name = claim.name
    imagerd_rt_dir = sentry_cfg.get("imagerd_rt_dir", "/usr/local/imagerd_rt")
    output_dir = sentry_cfg.get("output_dir", "")
    status_dir = cfg.get("status_dir") or str(Path.home() / ".every_camera" / "status")
    capture_seconds = sentry_cfg.get("capture_seconds", SENTRY_CAPTURE_SECONDS)

    dash = console_ui.start_dashboard("sentry", instance_name, verbose=verbose)
    # Before the camera is opened, so a camera that will not open still raises an alert.
    # The crash handler goes first: it alone can speak for a process killed outright.
    alert_status_path = os.path.join(status_dir, f"{os.getpid()}.json")
    alerts.install_crash_handler(alert_status_path)
    alerts.start(cfg.get("alerts", {}), node_name, instance_name, "sentry",
                 log_path=console_ui.default_log_path("sentry", instance_name),
                 status_path=alert_status_path)

    dash.update(status="starting", node_name=node_name, output_dir=output_dir,
                frames=0, errors=0)
    dash.set_section("device", [
        ("imagerd_rt dir:", imagerd_rt_dir),
        ("Publish at:", f"{capture_seconds} s of each minute"),
    ])

    cam = SentryCamera(imagerd_rt_dir)
    server = None
    try:
        if not cam.is_available():
            console_ui.error(f"imagerd_rt not found at: {imagerd_rt_dir} — set "
                             f"sentry.imagerd_rt_dir in config.json.")
            return

        if preview:
            run_preview_sentry(cam, instance_name)
            return

        # Without slots or a leftover schedule.conf imagerd_rt has no programme: that is
        # setup mode, not a failure.
        if sentry_cfg.get("slots"):
            try:
                cam.write_schedule_conf(sentry_cfg)
            except Exception as exc:
                console_ui.warn(f"Could not write schedule.conf: {exc}")
        elif not os.path.exists(os.path.join(imagerd_rt_dir, "schedule.conf")):
            setup_mode = True
        if setup_mode:
            announce_setup_mode("sentry.slots is empty and no schedule.conf "
                                "exists in " + imagerd_rt_dir)

        if not output_dir:
            console_ui.log("sentry.output_dir not set. Status still works; "
                           "FITS archives go wherever imagerd_rt is configured.")

        os.makedirs(status_dir, exist_ok=True)
        if output_dir:
            os.makedirs(output_dir, exist_ok=True)


        # A frame server failure is never fatal.
        from camera_service import CameraService
        from frame_server import start_frame_server
        # The schedule belongs to imagerd_rt, so no remote parameters and no pausing for
        # live frames: stopping that daemon would reach into another program's run.
        service = CameraService("sentry", instance_name, output_dir,
                                supports_params=False, supports_hold=False,
                                node_name=node_name, setup_mode=setup_mode)
        server = start_frame_server(cfg.get("server", {}), service)
        if server:
            dash.update(server_url=server.url)
            if setup_mode:
                console_ui.log(f"Focus this camera with: python focus_app.py "
                               f"--host {get_local_ip()} --port {server.port}")

        worker = SentryWorkerConsole(
            cam=cam,
            output_dir=output_dir,
            instance_name=instance_name,
            status_dir=status_dir,
            capture_seconds=capture_seconds,
            service=service,
            node_name=node_name,
            setup_mode=setup_mode,
        )

        def _stop(sig, frame):
            console_ui.log(f"{stop_signal_name(sig)} — stopping…")
            worker.request_stop()
        install_stop_handler(_stop)

        console_ui.log("Starting. Press Ctrl+C to stop.")
        worker.start()
        while worker.is_alive():
            worker.join(timeout=0.5)
    finally:
        if server:
            server.stop()
        dash.stop()
        claim.release()
